#!/usr/bin/env python3
"""Regenerates test/support/expected-columns.ts from src/database/schema.ts.
The schema-drift integration test then compares those TypeScript types with the
migrated database; `npm run typecheck` checks the generated map against the types."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
schema = (root / 'src/database/schema.ts').read_text()
interfaces = dict(re.findall(r'export interface (\w+Table) \{(.*?)\n\}', schema, re.S))
db = re.search(r'export interface DB \{(.*?)\n\}', schema, re.S).group(1)
out = ["import type { DB } from '../../src/database/schema';", '',
       '// GENERATED by api/scripts/gen-expected-columns.py; do not edit by hand.',
       'type ColumnsOf<Table> = { [Column in keyof Table]-?: true };',
       'type ExpectedColumnMap = { [Table in keyof DB]: ColumnsOf<DB[Table]> };', '',
       'const map: ExpectedColumnMap = {']
for table, iface in re.findall(r'\n  (\w+): (\w+Table);', db):
    cols = re.findall(r'\n  (\w+)\??:', interfaces[iface])
    out.append(f'  {table}: {{')
    out += [f'    {c}: true,' for c in cols]
    out.append('  },')
out += ['};', '', 'export const EXPECTED_COLUMNS: Record<string, string[]> = Object.fromEntries(',
        '  Object.entries(map).map(([table, columns]) => [table, Object.keys(columns)]),', ');', '']
(root / 'test/support/expected-columns.ts').write_text('\n'.join(out))
print('ok')
